#
#  Writes demos/tokenizer/tok/unicode_classes.hpp: the class of every code point as the GPT-4 and cl100k split
#  patterns see it - letter (\p{L}), number (\p{N}), whitespace (\s, which in Rust's regex, and so in tiktoken, is
#  \p{White_Space}), or other. Two stages: the high bits of a code point pick a block of 256, and each block packs
#  four code points to a byte, two bits each. Identical blocks are stored once.
#
#  Needs the regex module (pip install regex). The tables follow its Unicode version, printed into the header;
#  tiktoken's follow Rust's regex-syntax. They can differ only on code points assigned between the two versions,
#  and tokenizer_bench checks every token of its corpus against tiktoken's.
#
#      python scripts/tokenizer/generate_unicode_classes.py            # writes the header
#      python scripts/tokenizer/generate_unicode_classes.py --check    # exits 1 if the committed header differs

import pathlib
import sys

import regex

OTHER, LETTER, NUMBER, SPACE = 0, 1, 2, 3
L, N, S = regex.compile(r"\p{L}"), regex.compile(r"\p{N}"), regex.compile(r"\p{White_Space}")


def cls(cp: int) -> int:
    if 0xD800 <= cp <= 0xDFFF:
        return OTHER
    c = chr(cp)
    if L.match(c):
        return LETTER
    if N.match(c):
        return NUMBER
    if S.match(c):
        return SPACE
    return OTHER


def build():
    blocks, index, stage1 = [], {}, []
    for hi in range(0x110000 >> 8):
        packed = bytearray(64)
        for lo in range(256):
            packed[lo >> 2] |= cls((hi << 8) | lo) << ((lo & 3) * 2)
        key = bytes(packed)
        if key not in index:
            index[key] = len(blocks)
            blocks.append(key)
        stage1.append(index[key])
    assert len(blocks) <= 256
    return stage1, blocks


def render(stage1, blocks) -> str:
    out = []
    w = out.append
    w("//\n//  unicode_classes.hpp\n//  TSMoveables\n//\n//  Copyright 2010-2026 Saxon Herschel Nicholls\n//\n")
    w(f"//  GENERATED by scripts/tokenizer/generate_unicode_classes.py from the regex module's Unicode tables\n")
    w(f"//  (regex {regex.__version__}). Do not edit by hand.\n//\n")
    w("//  The class of a code point as the GPT-4 and cl100k split patterns see it: 0 other, 1 letter (\\p{L}),\n")
    w("//  2 number (\\p{N}), 3 whitespace (\\p{White_Space}). Two bits each, four to a byte, in blocks of 256.\n//\n\n")
    w("#ifndef ts_moveables_tokenizer_unicode_classes_hpp\n#define ts_moveables_tokenizer_unicode_classes_hpp\n\n")
    w("#include <cstdint>\n\nnamespace snicholls::tokenizer::detail\n{\n\n")
    w(f"inline constexpr std::uint8_t unicode_stage1[{len(stage1)}] = {{\n")
    for i in range(0, len(stage1), 24):
        w("    " + ", ".join(str(x) for x in stage1[i:i + 24]) + ",\n")
    w("};\n\n")
    w(f"inline constexpr std::uint8_t unicode_stage2[{len(blocks)} * 64] = {{\n")
    for b in blocks:
        for i in range(0, 64, 16):
            w("    " + ", ".join(f"0x{x:02x}" for x in b[i:i + 16]) + ",\n")
    w("};\n\n")
    w("/// \\brief The class of code point `cp` (at most 0x10FFFF): 0 other, 1 letter, 2 number, 3 whitespace.\n")
    w("constexpr unsigned unicode_class(std::uint32_t cp) noexcept\n{\n")
    w("    const unsigned block = unicode_stage1[cp >> 8];\n")
    w("    return (unicode_stage2[block * 64 + ((cp & 0xff) >> 2)] >> ((cp & 3) * 2)) & 3u;\n}\n\n")
    w("} // namespace snicholls::tokenizer::detail\n\n#endif // ts_moveables_tokenizer_unicode_classes_hpp\n")
    return "".join(out)


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    path = root / "demos/tokenizer/tok/unicode_classes.hpp"
    text = render(*build())
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != text:
            print(f"{path} is out of date: rerun {pathlib.Path(__file__).name}")
            sys.exit(1)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
